#!/usr/bin/env python3
"""Download the app's Google Fonts (Latin subset) for offline use.

Usage:
    python3 -I tools/fetch_fonts.py web/fonts

Writes <family>-<weight>.woff2 files plus fonts.css into the folder.
All three families are licensed under the SIL Open Font License 1.1
(see web/fonts/OFL.txt).
"""
import re
import sys
import urllib.request
from pathlib import Path

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Atkinson+Hyperlegible:wght@400;700"
    "&family=Baloo+2:wght@500;600;700"
    "&family=DM+Mono:wght@400;500&display=swap"
)
# A modern browser user agent makes Google Fonts serve woff2.
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
BLOCK_RE = re.compile(r"/\*\s*(?P<subset>[a-z-]+)\s*\*/\s*@font-face\s*{(?P<body>[^}]*)}", re.S)
WOFF2_MAGIC = b"wOF2"


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    css = get(CSS_URL).decode("utf-8")
    faces, seen_files = [], {}
    for m in BLOCK_RE.finditer(css):
        if m["subset"] != "latin":
            continue
        body = m["body"]
        family = re.search(r"font-family:\s*'([^']+)'", body)[1]
        weight = re.search(r"font-weight:\s*(\d+)", body)[1]
        url = re.search(r"src:\s*url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)", body)[1]
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", body)[1].strip()
        # Variable fonts share one file across weights; download each file once.
        if url not in seen_files:
            name = f"{family.replace(' ', '')}-{weight}.woff2"
            data = get(url)
            if not data.startswith(WOFF2_MAGIC):
                sys.exit(f"{url} is not a woff2 file")
            (out / name).write_bytes(data)
            seen_files[url] = name
        faces.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('{seen_files[url]}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n"
            "}\n"
        )
    if len(faces) != 7:
        sys.exit(f"Expected 7 font faces, got {len(faces)}")
    (out / "fonts.css").write_text(
        "/* Local copies of Atkinson Hyperlegible, Baloo 2 and DM Mono (Latin subset).\n"
        "   SIL Open Font License 1.1, see OFL.txt. Generated by tools/fetch_fonts.py. */\n"
        + "\n".join(faces),
        encoding="utf-8",
    )
    print(f"Wrote {len(seen_files)} font files and fonts.css to {out}")


if __name__ == "__main__":
    main()
