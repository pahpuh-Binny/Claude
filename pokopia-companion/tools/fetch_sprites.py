#!/usr/bin/env python3
"""Download Pokémon sprites from Pokémon Database and build species.js.

Usage:
    python3 -I tools/fetch_sprites.py web/sprites web/species.js

Reads the National Pokédex list from https://pokemondb.net/sprites (one
entry per species, in National Dex order). For each species it downloads
the Pokémon HOME render (falling back to the Scarlet & Violet icon),
trims the empty space around the Pokémon, scales it to fit 192x192 and
saves it as <slug>.webp in the sprites folder. It also writes species.js:

    window.POKOPIA_SPECIES = [["Bulbasaur", "bulbasaur"], ...]

where the array index + 1 is the National Pokédex number.

Already-downloaded sprites are skipped, so re-running only fetches new ones.
Sprites are © Nintendo / Creatures Inc. / GAME FREAK inc. They are bundled
for a personal, non-commercial fan app; see the README.
"""
import html
import io
import json
import re
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

INDEX_URL = "https://pokemondb.net/sprites"
ICON_RE = re.compile(
    r'<a class="infocard" href="/sprites/(?P<slug>[a-z0-9-]+)"><picture>.*?'
    r'<img class="img-fixed icon-pkmn" src="(?P<src>https://img\.pokemondb\.net/sprites/'
    r'scarlet-violet/icon/[a-z0-9-]+\.png)" alt="(?P<name>[^"]+)"',
    re.S,
)
HOME_URL = "https://img.pokemondb.net/sprites/home/normal/{slug}.png"
MAX_SIZE = (192, 192)
HEADERS = {"User-Agent": "PokopiaCompanion/1.0 (personal fan app sprite fetch)"}
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def download(url: str):
    """Return PNG bytes, None for a 404, or raise after retries."""
    for attempt in range(4):
        try:
            data = get(url)
            return data if data.startswith(PNG_MAGIC) else None
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return None
            if attempt == 3:
                raise
        except Exception:  # network hiccup: back off and retry
            if attempt == 3:
                raise
        time.sleep(2 ** attempt)


def fetch_one(entry, out_dir: Path):
    slug = entry["slug"]
    target = out_dir / f"{slug}.webp"
    if target.exists():
        return slug, "cached"
    try:
        data, kind = download(HOME_URL.format(slug=slug)), "ok"
        if data is None:
            data, kind = download(entry["src"]), "ok (icon fallback)"
    except Exception as exc:
        return slug, f"failed: {exc}"
    if data is None:
        return slug, "failed: no image"
    Image.open(io.BytesIO(data)).verify()
    img = Image.open(io.BytesIO(data)).convert("RGBA")
    bbox = img.getbbox()
    if bbox:
        img = img.crop(bbox)
    img.thumbnail(MAX_SIZE, Image.LANCZOS)
    img.save(target, "WEBP", quality=80, method=6)
    time.sleep(0.1)  # be gentle with the host
    return slug, kind


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    out_dir = Path(sys.argv[1])
    species_js = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    page = get(INDEX_URL).decode("utf-8")
    entries = [
        {"slug": m["slug"], "src": m["src"], "name": html.unescape(m["name"])}
        for m in ICON_RE.finditer(page)
    ]
    # Sanity checks on National Dex order.
    if len(entries) < 1025 or entries[0]["slug"] != "bulbasaur" or entries[24]["slug"] != "pikachu":
        sys.exit(f"Unexpected sprite list ({len(entries)} entries); page layout may have changed.")

    with ThreadPoolExecutor(max_workers=4) as pool:
        results = list(pool.map(lambda e: fetch_one(e, out_dir), entries))
    failed = [(s, r) for s, r in results if r.startswith("failed")]
    fetched = sum(1 for _, r in results if r.startswith("ok"))
    fallbacks = [s for s, r in results if r == "ok (icon fallback)"]
    print(f"{len(entries)} species, {fetched} downloaded, {len(entries) - fetched - len(failed)} cached, {len(failed)} failed")
    if fallbacks:
        print("Used the small icon for:", ", ".join(fallbacks))
    for slug, reason in failed:
        print(f"  {slug}: {reason}")

    species = [[e["name"], e["slug"]] for e in entries]
    species_js.write_text(
        "/* National Pokédex names and sprite slugs. Index + 1 = Pokédex number.\n"
        "   Generated by tools/fetch_sprites.py from pokemondb.net/sprites. */\n"
        "window.POKOPIA_SPECIES = "
        + json.dumps(species, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {species_js}")
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
