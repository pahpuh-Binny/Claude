#!/usr/bin/env python3
"""Generate the CYD firmware's data and sprite sources from the web app.

Usage (from pokopia-companion/):
    python3 tools/gen_cyd_assets.py

Reads web/data.js, web/species.js and web/sprites/ and writes:
    cyd/src/gen/game_data.h, game_data.cpp   guide data as C++ tables
    cyd/src/gen/species.cpp                  all 1,025 names and app ids
    cyd/src/gen/sprites.cpp                  built-in Pokémon sprites (RGB565A8)

Needs Node.js (to read the JS data files) and Pillow.
web/ stays the single source of truth: edit data.js, then re-run this.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from PIL import Image  # noqa: E402

import lvgl_image  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "cyd" / "src" / "gen"

SPRITE_L = (80, 74)   # detail screens
SPRITE_S = (32, 30)   # lists, chips and home tiles

# Same id rules as app.js's slug(), so save codes match the phone app.
NODE_DUMP = r"""
global.window = {};
require(process.argv[1] + '/data.js');
require(process.argv[1] + '/species.js');
const slug = (s) => String(s).toLowerCase().normalize('NFKD')
  .replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const D = window.POKOPIA_DATA;
D.pokemon.forEach((p) => { p.id = slug(p.name); });
const species = window.POKOPIA_SPECIES.map(([name, file]) => ({ name, file, id: slug(name) }));
process.stdout.write(JSON.stringify({ data: D, species }));
"""

TILE_RULES = [  # mirrors tileClass() in app.js
    (r"ocean|sea", "T_OCEAN"),
    (r"water|pond|duckweed|river", "T_WATER"),
    (r"tree|shrub|bush", "T_TREE"),
    (r"flower|blossom|petal", "T_FLOWER"),
    (r"grass|hedge|moss|leaf|vine", "T_GRASS"),
    (r"fire|torch|lamp|lantern|ember", "T_FIRE"),
    (r"rock|stone|boulder|iron|metal|ore", "T_ROCK"),
    (r"sand|soil|dirt|mud", "T_SOIL"),
]


def tile_for(material: str) -> str:
    s = material.lower()
    for pattern, tile in TILE_RULES:
        if re.search(pattern, s):
            return tile
    return "T_WOOD"


def c_str(value) -> str:
    if value is None or value == "":
        return "nullptr"
    return json.dumps(str(value), ensure_ascii=False)


def c_bool(value) -> str:
    return "true" if value else "false"


def str_array(name: str, items) -> str:
    if not items:
        return f"static const char* const {name}[] = {{ nullptr }};\n"
    body = ",\n    ".join(c_str(i) for i in items)
    return f"static const char* const {name}[] = {{\n    {body}\n}};\n"


def main():
    dump = subprocess.run(
        ["node", "-e", NODE_DUMP, str(WEB)], check=True, capture_output=True, text=True
    ).stdout
    payload = json.loads(dump)
    D, species = payload["data"], payload["species"]
    dex_of = {s["name"].lower(): i + 1 for i, s in enumerate(species)}
    spec_index = {s["id"]: i for i, s in enumerate(D["specialties"])}
    area_index = {a["id"]: i for i, a in enumerate(D["areas"])}
    OUT.mkdir(parents=True, exist_ok=True)

    # ---------- game_data.cpp ----------
    cpp = ['// Generated by tools/gen_cyd_assets.py from web/data.js. Do not edit.\n',
           '#include "game_data.h"\n\nnamespace gd {\n\n']

    for i, s in enumerate(D["specialties"]):
        cpp.append(str_array(f"SPEC_EX_{i}", s["examples"]))
    cpp.append("const Spec SPECS[] = {\n")
    for i, s in enumerate(D["specialties"]):
        cpp.append(f'    {{{c_str(s["id"])}, {c_str(s["name"])}, {c_str(s["does"])}, SPEC_EX_{i}, '
                   f'{len(s["examples"])}, {c_bool(s.get("verify"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_SPECS = {len(D['specialties'])};\n\n")

    cpp.append("const Mon MONS[] = {\n")
    sprite_dexes = set()
    for p in D["pokemon"]:
        specs = [spec_index[x] for x in p.get("specs", [])][:3]
        specs_c = ", ".join(str(x) for x in specs + [0] * (3 - len(specs)))
        sprite_dex = dex_of[(p.get("base") or p["name"]).lower()]
        sprite_dexes.add(sprite_dex)
        cpp.append(
            f'    {{{c_str(p["id"])}, {c_str(p["name"])}, {p["dex"] or 0}, {sprite_dex}, {c_str(p.get("base"))}, '
            f'{{{specs_c}}}, {len(specs)}, {c_str(p.get("where"))}, {c_str(p.get("role"))}, '
            f'{c_str(p.get("note"))}, {c_bool(p.get("verify"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint16_t N_MONS = {len(D['pokemon'])};\n\n")

    for i, h in enumerate(D["habitats"]):
        reqs = ", ".join(f'{{{c_str(m)}, {n}, {tile_for(m)}}}' for m, n in h["req"])
        cpp.append(f"static const Req HAB_REQ_{i}[] = {{ {reqs} }};\n")
        cpp.append(str_array(f"HAB_RES_{i}", h.get("residents", [])))
    cpp.append("const Habitat HABITATS[] = {\n")
    for i, h in enumerate(D["habitats"]):
        cpp.append(
            f'    {{{c_str(h["id"])}, {h["no"] or 0}, {c_str(h["name"])}, HAB_REQ_{i}, {len(h["req"])}, '
            f'HAB_RES_{i}, {len(h.get("residents", []))}, {c_str(h.get("cond"))}, {c_str(h.get("note"))}, '
            f'{c_bool(h.get("verify"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_HABITATS = {len(D['habitats'])};\n\n")

    cpp.append("const Move MOVES[] = {\n")
    for m in D["moves"]:
        from_dex = dex_of[m["from"].lower()]
        sprite_dexes.add(from_dex)
        area = area_index.get(m.get("area"), -1) if m.get("area") else -1
        cpp.append(
            f'    {{{c_str(m["id"])}, {c_str(m["name"])}, {c_str(m["from"])}, {from_dex}, {area}, '
            f'{c_str(m["use"])}, {c_str(m.get("meal"))}, {c_str(m.get("note"))}, {c_bool(m.get("verify"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_MOVES = {len(D['moves'])};\n\n")

    for i, a in enumerate(D["areas"]):
        cpp.append(str_array(f"AREA_GOALS_{i}", a.get("goals", [])))
    cpp.append("const Area AREAS[] = {\n")
    for i, a in enumerate(D["areas"]):
        cpp.append(
            f'    {{{c_str(a["id"])}, {c_str(a["name"])}, {a["step"]}, {c_str(a.get("inspired"))}, '
            f'{c_str(a["summary"])}, AREA_GOALS_{i}, {len(a.get("goals", []))}, {c_str(a.get("unlocks"))}, '
            f'{c_str(a.get("note"))}, {c_bool(a.get("verify"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_AREAS = {len(D['areas'])};\n\n")

    cpp.append("const Meal MEALS[] = {\n")
    for m in D["meals"]:
        cpp.append(f'    {{{c_str(m["meal"])}, {c_str(m["tool"])}, {c_bool(m["heat"])}, '
                   f'{c_str(m["move"])}, {c_str(m["starter"])}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_MEALS = {len(D['meals'])};\n\n")

    for name, key in [("TIPS", "tips"), ("COOKING_NOTES", "cookingNotes"), ("CRAFTING", "crafting"),
                      ("MULTIPLAYER", "multiplayer")]:
        items = D[key]
        cpp.append(f"const char* const {name}[] = {{\n    " + ",\n    ".join(c_str(t) for t in items) + "\n};\n")
        cpp.append(f"const uint8_t N_{name} = {len(items)};\n\n")

    starters = D["starterRequests"]
    cpp.append("const StarterRequest STARTER_REQUESTS[] = {\n")
    for r in starters:
        cpp.append(f'    {{{c_str(r["text"])}, {c_str(r.get("area"))}}},\n')
    cpp.append("};\n")
    cpp.append(f"const uint8_t N_STARTER_REQUESTS = {len(starters)};\n\n")

    meta = D["meta"]
    cpp.append(f'const char* const COOKING_UNLOCK_NOTE = {c_str(D["cookingUnlock"]["note"])};\n')
    cpp.append(f'const char* const POWER_UP_NOTE = {c_str(D["powerUpNote"])};\n')
    cpp.append(f'const char* const META_GAME = {c_str(meta["game"])};\n')
    cpp.append(f'const char* const META_PLATFORM = {c_str(meta["platform"])};\n')
    cpp.append(f'const char* const META_RELEASED = {c_str(meta["released"])};\n')
    cpp.append(f'const char* const META_UPDATED = {c_str(meta["updated"])};\n')
    cpp.append(f'const uint16_t META_HABITAT_TOTAL = {meta["habitatTotal"]};\n')
    cpp.append("\n}  // namespace gd\n")
    (OUT / "game_data.cpp").write_text("".join(cpp), encoding="utf-8")

    # ---------- species.cpp ----------
    names = ",\n    ".join(c_str(s["name"]) for s in species)
    ids = ",\n    ".join(c_str(s["id"]) for s in species)
    (OUT / "species.cpp").write_text(
        "// Generated by tools/gen_cyd_assets.py from web/species.js. Do not edit.\n"
        '#include "game_data.h"\n\nnamespace gd {\n\n'
        f"const char* const SPECIES_NAMES[] = {{\n    {names}\n}};\n\n"
        "// Ids follow the phone app's slug rules so save codes line up.\n"
        f"const char* const SPECIES_IDS[] = {{\n    {ids}\n}};\n\n"
        f"const uint16_t N_SPECIES = {len(species)};\n\n}}  // namespace gd\n",
        encoding="utf-8")

    # ---------- sprites.cpp ----------
    sprite_dexes = sorted(sprite_dexes)
    parts = ['// Generated by tools/gen_cyd_assets.py from web/sprites/. Do not edit.\n'
             '// Pokémon images © Nintendo, Creatures Inc. and GAME FREAK inc.\n'
             '#include "game_data.h"\n\nnamespace gd {\n\n']
    total = 0
    for dex in sprite_dexes:
        src = WEB / "sprites" / f"{species[dex - 1]['file']}.webp"
        base = Image.open(src)
        for suffix, box in (("l", SPRITE_L), ("s", SPRITE_S)):
            img = lvgl_image.fit(base, *box)
            data = lvgl_image.rgb565a8(img)
            total += len(data)
            hexdata = ",".join(f"0x{b:02x}" for b in data)
            parts.append(
                f"static const uint8_t SPR_{dex}_{suffix}_DATA[] = {{{hexdata}}};\n"
                f"static const lv_image_dsc_t SPR_{dex}_{suffix} = {{\n"
                f"    {{LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565A8, 0, {img.width}, {img.height}, "
                f"{img.width * 2}, 0}},\n"
                f"    {len(data)}, SPR_{dex}_{suffix}_DATA, nullptr\n}};\n")
    parts.append("const SpriteRef BUILTIN_SPRITES[] = {\n")
    for dex in sprite_dexes:
        parts.append(f"    {{{dex}, &SPR_{dex}_l, &SPR_{dex}_s}},\n")
    parts.append("};\n")
    parts.append(f"const uint16_t N_BUILTIN_SPRITES = {len(sprite_dexes)};\n\n}}  // namespace gd\n")
    (OUT / "sprites.cpp").write_text("".join(parts), encoding="utf-8")

    print(f"{len(D['pokemon'])} Pokémon, {len(D['habitats'])} habitats, {len(D['moves'])} moves, "
          f"{len(species)} species, {len(sprite_dexes)} built-in sprites ({total / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
